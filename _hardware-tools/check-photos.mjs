// Checks the Hardware photos before they're published, then regenerates _data/hardware/photos.yml from them.
//
// The media folder (default .artifacts/hardware-media, git-ignored) mirrors the public media/hardware/ path:
//   banner.jpg                      long edge <= 2000 px, no small copy
//   <project>/<name>.jpg            long edge <= 1400 px
//   <project>/<name>-sm.jpg         long edge <= 640 px
// <project> is the page's permalink slug. Names are lowercase words joined by hyphens.
//
// Fails on any photo that still carries metadata (EXIF, XMP, IPTC or comments: camera, GPS, timestamps), is too big,
// lacks its small copy, or that a page or data file references but doesn't exist.
//
// node check-photos.mjs [folder]            check, then write photos.yml
// node check-photos.mjs [folder] --check    check, and fail if photos.yml is out of date (upload-media.ps1 runs this)
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const PAGES = path.join(ROOT, '_pages', 'hardware');
const DATA = path.join(ROOT, '_data', 'hardware');
const OUT = path.join(DATA, 'photos.yml');
const HEADER = '# Photo sizes [width, height, small width] by project/name, so pages reserve space before photos load.\n'
  + '# Generated by _hardware-tools/check-photos.mjs from the published copies; do not edit by hand.\n';
const MAX = { banner: 2000, photo: 1400, small: 640 };
const NAME = /^[a-z0-9]+(?:-[a-z0-9]+)*$/;

// [width, height] and any metadata segments, read from the segments before the image data.
// APP0 (JFIF) and APP2 (ICC colour profile) are fine; every other APPn segment and COM carries metadata.
export function readJpeg(b) {
  if (b[0] !== 0xff || b[1] !== 0xd8) throw new Error('not a JPEG');
  let size;
  const metadata = [];
  for (let i = 2; i + 4 <= b.length;) {
    if (b[i] !== 0xff) throw new Error(`corrupt segment at byte ${i}`);
    const m = b[i + 1];
    if (m === 0xff) { i++; continue; }
    if (m === 0xda || m === 0xd9) break;
    const len = b.readUInt16BE(i + 2);
    if (m >= 0xc0 && m <= 0xcf && ![0xc4, 0xc8, 0xcc].includes(m)) size ??= [b.readUInt16BE(i + 7), b.readUInt16BE(i + 5)];
    if ((m >= 0xe1 && m <= 0xef && m !== 0xe2) || m === 0xfe) metadata.push(m === 0xfe ? 'comment' : `APP${m - 0xe0}`);
    i += 2 + len;
  }
  if (!size) throw new Error('no frame header');
  return { size, metadata };
}

// Every photo key ("windlass/final") the pages and data files use. A bare name in a page is that page's own photo.
function references() {
  const refs = new Map([['banner', 'the Hardware index']]);
  const field = /^\s*(?:-\s*)?(cover|before|after|photo):\s*"?([^"\s#]+)"?\s*$/;
  for (const f of fs.readdirSync(PAGES).filter(f => f.endsWith('.md'))) {
    const front = fs.readFileSync(path.join(PAGES, f), 'utf8').split(/^---\s*$/m)[1] ?? '';
    const project = front.match(/^permalink:\s*(\S+)/m)?.[1].split('/').filter(Boolean).pop();
    for (const line of front.split('\n')) {
      const v = line.match(field)?.[2];
      if (v) refs.set(v.includes('/') ? v : `${project}/${v}`, `_pages/hardware/${f}`);
    }
  }
  for (const f of fs.readdirSync(DATA).filter(f => f.endsWith('.yml') && f !== 'photos.yml')) {
    for (const line of fs.readFileSync(path.join(DATA, f), 'utf8').split('\n')) {
      const v = line.match(field)?.[2];
      if (v) refs.set(v, `_data/hardware/${f}`);
    }
  }
  return refs;
}

function run(dir, check) {
  const problems = [];
  const notes = [];
  const sizes = new Map();
  if (!fs.existsSync(dir)) return { problems: [`no media folder: ${dir}`], notes };
  for (const rel of fs.readdirSync(dir, { recursive: true }).map(f => f.split(path.sep).join('/')).sort()) {
    const file = path.join(dir, rel);
    if (fs.statSync(file).isDirectory()) continue;
    if (!rel.endsWith('.jpg')) { notes.push(`not published (only .jpg is): ${rel}`); continue; }
    const key = rel.slice(0, -4);
    const parts = key.split('/');
    const small = key.endsWith('-sm');
    if (!(key === 'banner' || (parts.length === 2 && parts.every(p => NAME.test(p))))) {
      problems.push(`${rel}: expected banner.jpg or <project>/<name>.jpg in lowercase-hyphenated names`);
      continue;
    }
    let jpeg;
    try { jpeg = readJpeg(fs.readFileSync(file)); } catch (e) { problems.push(`${rel}: ${e.message}`); continue; }
    if (jpeg.metadata.length) problems.push(`${rel}: carries metadata (${jpeg.metadata.join(', ')}); re-run prepare-photos.mjs`);
    const max = key === 'banner' ? MAX.banner : small ? MAX.small : MAX.photo;
    if (Math.max(...jpeg.size) > max) problems.push(`${rel}: ${jpeg.size.join('x')} is over ${max} px on its long edge`);
    sizes.set(key, jpeg.size);
  }

  const photos = {};
  for (const [key, size] of sizes) {
    if (key.endsWith('-sm')) {
      if (!sizes.has(key.slice(0, -3))) problems.push(`${key}.jpg has no full-size photo`);
      continue;
    }
    if (key === 'banner') { photos[key] = size; continue; }
    const sm = sizes.get(`${key}-sm`);
    if (!sm) problems.push(`${key}.jpg has no small copy (${key}-sm.jpg)`);
    else photos[key] = [...size, sm[0]];
  }

  const refs = references();
  for (const [key, where] of refs) if (!sizes.has(key)) problems.push(`${where} uses ${key}, which isn't in the media folder`);
  for (const key of Object.keys(photos)) if (!refs.has(key)) notes.push(`unused: ${key}`);

  const keys = Object.keys(photos).filter(k => k !== 'banner').sort();
  const yml = HEADER + ['banner', ...keys].filter(k => photos[k]).map(k => `${k}: [ ${photos[k].join(', ')} ]\n`).join('');
  if (!problems.length) {
    const current = fs.existsSync(OUT) ? fs.readFileSync(OUT, 'utf8').replace(/\r\n/g, '\n') : '';
    if (current === yml) notes.push(`photos.yml is up to date (${keys.length} photos)`);
    else if (check) problems.push('_data/hardware/photos.yml is out of date: run `npm run sizes` and commit it');
    else { fs.writeFileSync(OUT, yml); notes.push(`wrote _data/hardware/photos.yml (${keys.length} photos)`); }
  }
  return { problems, notes };
}

if (import.meta.url === pathToFileURL(process.argv[1]).href) {
  const args = process.argv.slice(2);
  const dir = path.resolve(args.find(a => !a.startsWith('--')) ?? path.join(ROOT, '.artifacts', 'hardware-media'));
  const { problems, notes } = run(dir, args.includes('--check'));
  for (const n of notes) console.log(n);
  for (const p of problems) console.error(`problem: ${p}`);
  process.exitCode = problems.length ? 1 : 0;
}
